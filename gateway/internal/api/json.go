package api

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log"
	"net/http"
)

const jsonContentType = "application/json; charset=utf-8"

func decodeJSON(body io.Reader, dst any) error {
	decoder := json.NewDecoder(body)
	if err := decoder.Decode(dst); err != nil {
		return fmt.Errorf("invalid JSON: %w", err)
	}
	if err := decoder.Decode(new(json.RawMessage)); err != io.EOF {
		return errors.New("request body must contain exactly one JSON object")
	}
	return nil
}

func writeError(w http.ResponseWriter, status int, message string) {
	WriteJSON(w, status, map[string]string{"error": message})
}

func WriteJSON(w http.ResponseWriter, status int, body any) {
	data, err := json.Marshal(body)
	if err != nil {
		log.Printf("encode JSON response: %v", err)
		status = http.StatusInternalServerError
		data = []byte(`{"error":"internal server error"}`)
	}

	w.Header().Set("Content-Type", jsonContentType)
	w.WriteHeader(status)
	if _, err := w.Write(append(data, '\n')); err != nil {
		log.Printf("write JSON response: %v", err)
	}
}

// JSONResponses formats responses generated by ServeMux itself.
func JSONResponses(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		next.ServeHTTP(&jsonResponseWriter{ResponseWriter: w}, r)
	})
}

type jsonResponseWriter struct {
	http.ResponseWriter
	wroteHeader  bool
	replacedBody bool
}

func (w *jsonResponseWriter) WriteHeader(status int) {
	if w.wroteHeader {
		return
	}
	w.wroteHeader = true

	if w.Header().Get("Content-Type") != jsonContentType {
		if status >= http.StatusBadRequest {
			w.replacedBody = true
			writeError(w.ResponseWriter, status, http.StatusText(status))
			return
		}
		if location := w.Header().Get("Location"); status >= http.StatusMultipleChoices && status < http.StatusBadRequest && location != "" {
			w.replacedBody = true
			WriteJSON(w.ResponseWriter, status, map[string]string{"location": location})
			return
		}
	}
	w.Header().Set("Content-Type", jsonContentType)
	w.ResponseWriter.WriteHeader(status)
}

func (w *jsonResponseWriter) Write(data []byte) (int, error) {
	if !w.wroteHeader {
		w.WriteHeader(http.StatusOK)
	}
	if w.replacedBody {
		return len(data), nil
	}
	return w.ResponseWriter.Write(data)
}
